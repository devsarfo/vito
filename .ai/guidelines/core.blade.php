# Important Guidelines

These rules override any other similar rules mentioned above!

## Code formatting

Never run `pint` or `format` or `lint` commands.

## Running the app

Never run the app server like `artisan serve` as it is already running. Never run npm dev or build commands.

## Testing

If tests failing more than 3 times, stop retrying and inform the user to review.

When creating tests, follow the existing test structure and naming conventions in the project.

## Routes

This project doesn't have routes directory and it uses Spatie route attributes instead. Don't change this.

